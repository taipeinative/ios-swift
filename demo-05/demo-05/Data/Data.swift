import SwiftUI

struct CustomColor: Identifiable, Hashable {
    let id = UUID()
    let name: String
    let r: Double
    let g: Double
    let b: Double
    
    var color: Color {
        Color(red: r/255, green: g/255, blue: b/255)
    }
    
    // Distance function
    func distance(to other: CustomColor) -> Double {
        let dr = r - other.r
        let dg = g - other.g
        let db = b - other.b
        return dr*dr + dg*dg + db*db
    }
}

